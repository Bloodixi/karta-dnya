function hash(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

/** Ответ на желание по карте: да / скорее да / не сейчас; формулировка стабильна для карты и положения. */
export function wishAnswer(slug: string, reversed: boolean): WishAnswer {
  let tone: WishTone;
  if (WISH_CARDS.has(slug)) tone = reversed ? "likely" : "yes";
  else {
    const v = tarotVerdict(slug, reversed);
    tone = v.tone === "yes" ? (v.answer === "Да" ? "yes" : "likely") : "later";
  }
  const b = BANK[tone];
  return { answer: b.answer, tone, text: b.texts[hash(`${slug}:${reversed ? 1 : 0}`) % b.texts.length] };
}
