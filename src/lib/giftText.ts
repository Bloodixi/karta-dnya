/**
 * Проверка текстов подарка (подпись и пожелание) — общая для сервера (razborGift.ts) и формы в браузере.
 * Без серверных зависимостей.
 */

/** NFKC и без невидимых форматирующих символов (мягкий перенос, нулевой пробел, BOM…): проверяем ровно то, что храним. */
export const normGiftText = (s: string) => s.normalize("NFKC").replace(/\p{Cf}+/gu, "").replace(/[。．｡]/g, ".");

/** Кириллические доменные зоны: «слово.рф» — ссылка, «рождения.Будь» — опечатка. */
const CYR_ZONES = "рф|рус|москва|онлайн|сайт|дети|орг|ком|укр|бел|қаз|срб|мкд|мон|католик";

/**
 * Подпись и пожелание уходят чужому человеку от имени сайта — ссылок и адресов в них быть не должно.
 * Запрет: «схема://», mailto:/tel:/javascript:/data:, «@», «www», IPv4 из четырёх групп и «слово.зона», где зона —
 * латиница от 2 букв (любые домены и punycode) или кириллическая зона из списка. Даты («14.03.1991», «к 25.12»)
 * и пропущенный пробел после точки («рождения.Будь») ссылкой не считаются.
 */
const LINKISH = [
  /[a-z][a-z0-9+.-]*:\/\//i,
  /\b(?:mailto|tel|javascript|data):/i,
  /@/,
  /(?<![\d.])\d{1,3}(?:\.\d{1,3}){3}(?![\d.]*\d)/,
  /\bwww\b/i,
  /[\p{L}\p{N}-]\.[a-z]{2,}/iu,
  new RegExp(`[\\p{L}\\p{N}-]\\.(?:${CYR_ZONES})(?![\\p{L}\\p{N}])`, "iu"),
];

/** Есть ли в тексте что-то похожее на ссылку или адрес. */
export function giftHasLink(v: string): boolean {
  const s = normGiftText(v);
  return LINKISH.some((re) => re.test(s));
}
