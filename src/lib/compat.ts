function pairKey(a: Element, b: Element): string {
  return ELEMENT_BASE[`${a}-${b}`] !== undefined ? `${a}-${b}` : `${b}-${a}`;
}

export type Compat = {
  a: Zodiac; b: Zodiac; score: number; love: number; friendship: number; work: number;
  text: { general: string; love: string; life: string; advice: string }; verdict: string;
};

export function compatibility(a: Zodiac, b: Zodiac): Compat {
  const key = pairKey(a.element as Element, b.element as Element);
  let score = ELEMENT_BASE[key] ?? 60;
  if (a.compatibility.best.includes(b.slug)) score += 10;
  if (b.compatibility.best.includes(a.slug)) score += 6;
  if (a.compatibility.hard.includes(b.slug)) score -= 10;
  if (b.compatibility.hard.includes(a.slug)) score -= 6;
  if (a.slug === b.slug) score -= 4;
  score = Math.max(35, Math.min(97, score));
  const spread = (a.slug.length + b.slug.length) % 7;
  const love = Math.max(30, Math.min(99, score + (spread - 3)));
  const friendship = Math.max(30, Math.min(99, score + ((spread * 2) % 5) - 1));
  const work = Math.max(30, Math.min(99, score + ((spread * 3) % 7) - 4));
  const verdict = score >= 85 ? "отличная пара" : score >= 70 ? "хорошая совместимость" : score >= 55 ? "средняя, нужна работа над отношениями" : "сложная пара, но не безнадёжная";
  return { a, b, score, love, friendship, work, text: PAIR_TEXT[key], verdict };
}

export function allPairs(): { a: Zodiac; b: Zodiac; slug: string }[] {
  const z = getZodiac();
  const out: { a: Zodiac; b: Zodiac; slug: string }[] = [];
  for (const a of z) for (const b of z) out.push({ a, b, slug: `${a.slug}-${b.slug}` });
  return out;
}

export function parsePair(slug: string): { a: Zodiac; b: Zodiac } | null {
  const z = getZodiac();
  for (const a of z) {
    if (!slug.startsWith(a.slug + "-")) continue;
    const rest = slug.slice(a.slug.length + 1);
    const b = z.find((x) => x.slug === rest);
    if (b) return { a, b };
  }
  return null;
}
