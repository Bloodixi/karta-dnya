def qkey(a, b):
    o = "кфм"
    return "".join(sorted([QK[a["quality"]], QK[b["quality"]]], key=o.index))


def pad(text: str, extra: str, lo=50) -> str:
    return text if words(text) >= lo else f"{text} {extra}"


def fit(parts: list[str], lo=50, hi=110, optional=()) -> str:
    """Собирает блок; если длиннее hi слов — выкидывает необязательные предложения по порядку."""
    keep = list(parts)
    for o in optional:
        if words(" ".join(keep)) <= hi:
            break
        if o in keep:
            keep.remove(o)
    t = " ".join(keep)
    return t


