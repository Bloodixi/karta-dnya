def gender(text: str, f: bool) -> str:
    return re.sub(r"\[([^|\]]+)\|([^\]]+)\]", lambda m: m.group(2 if f else 1), text)


def words(t: str) -> int:
    return len(re.findall(r"[\w-]+", t))


def score_of(a: dict, b: dict) -> int:
    key = f"{a['element']}-{b['element']}"
    if key not in ELEMENT_BASE:
        key = f"{b['element']}-{a['element']}"
    s = ELEMENT_BASE.get(key, 60)
    if b["slug"] in a["compatibility"]["best"]: s += 10
    if a["slug"] in b["compatibility"]["best"]: s += 6
    if b["slug"] in a["compatibility"]["hard"]: s -= 10
    if a["slug"] in b["compatibility"]["hard"]: s -= 6
    if a["slug"] == b["slug"]: s -= 4
    return max(35, min(97, s))


def spread(a, b):
    sp = (len(a["slug"]) + len(b["slug"])) % 7
    sc = score_of(a, b)
    return dict(love=max(30, min(99, sc + (sp - 3))), friendship=max(30, min(99, sc + ((sp * 2) % 5) - 1)),
                work=max(30, min(99, sc + ((sp * 3) % 7) - 4)))


def el_key(a, b):
    k = f"{a['element']}-{b['element']}"
    return k if k in EL else f"{b['element']}-{a['element']}"


def qual(a, b):
    qa, qb = QK[a["quality"]], QK[b["quality"]]
    order = "кфм"
    pair = sorted([(qa, a), (qb, b)], key=lambda x: order.index(x[0]))
    key = pair[0][0] + pair[1][0]
    q = QUAL[key]
    roles = {}
    for k, z in pair:
        roles[f"{ {'к': 'k', 'ф': 'f', 'м': 'm'}[k]}_ins".replace(" ", "")] = F[z["slug"]][3]
        roles[f"{ {'к': 'k', 'ф': 'f', 'м': 'm'}[k]}_dat".replace(" ", "")] = F[z["slug"]][2]
    lead = q["lead"].format(**roles)
    return lead, q["home"], q["work"]


